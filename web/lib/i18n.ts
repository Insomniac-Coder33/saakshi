const dicts: Record<Language, Dict> = { en, bn, hi };

export function t(lang: Language, key: StringKey, vars?: Record<string, string | number>): string {
  let s = dicts[lang][key] ?? en[key];
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, String(v));
  return s;
}

/** Digits in her script, for counts on Bengali and Hindi screens. */
export function digits(lang: Language, n: number | string): string {
  const s = String(n);
  if (lang === "bn") return s.replace(/\d/g, (d) => "০১২৩৪৫৬৭৮৯"[+d]);
  return s;
}

